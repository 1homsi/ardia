import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const url = process.argv[2] ?? "http://127.0.0.1:5191/?bare";
const output = resolve(process.argv[3] ?? ".omx/artifacts/bookmark-cascade/ui");
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_BINARY ? { executablePath: process.env.CHROME_BINARY } : {}) });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 });
const moduleUrl = "/@fs" + fileURLToPath(new URL("../../../apps/browser/src/state/import/apply.ts", import.meta.url));
await mkdir(output, { recursive: true });
try {
  await page.goto(url);
  await page.waitForFunction(() => !!globalThis.ardiaDemo);
  await page.evaluate(async (moduleUrl) => {
    const store = globalThis.ardiaDemo.store;
    const s = store.getState();
    const tabs = Object.fromEntries(["t_browser", "t_vite", "t_pin_mdn"].map((id) => [id, s.tabs[id]]));
    store.setState({ tabs, groups: {}, profiles: { ...s.profiles, default: { ...s.profiles.default, name: "papers", pinnedCollapsed: false } }, windows: { w_demo: { ...s.windows.w_demo, tabIds: Object.keys(tabs) } }, settings: { ...s.settings, sidebarWidth: 260, theme: "light" } });
    const { importArcSpace } = await import(moduleUrl);
    const names = ["Deep Learning Alchemy", "Chatbot", "OCR", "Deep Learning Theory", "Distributed Systems", "Learn Go with Tests"];
    importArcSpace("default", { id: "papers", name: "papers", profileId: "Default", pinned: Array.from({ length: 36 }, (_, i) => ({ type: "url", url: `https://example.org/paper/${i}`, title: `${names[i % names.length]} ${i + 1}`, pageTitle: `Source page ${i + 1}` })), tabs: [] });
    importArcSpace("p_work", { id: "work", name: "Work", profileId: "Default", pinned: [{ type: "url", url: "https://example.org/work", title: "Work bookmark" }], tabs: [] });
  }, moduleUrl);
  const sidebar = page.locator(".ardia-window");
  const capture = (name) => sidebar.screenshot({ path: resolve(output, name + ".png"), animations: "disabled" });
  await capture("expanded");
  const header = page.getByRole("button", { name: "Collapse Pinned Tabs · papers", exact: true });
  assert.ok(await header.isVisible(), "the expanded Space has a visible disclosure above its bookmarks");
  const headerBox = await header.boundingBox();
  const firstBox = await page.getByText("Deep Learning Alchemy 1", { exact: true }).boundingBox();
  assert.ok(headerBox && firstBox && headerBox.y + headerBox.height <= firstBox.y + 1);
  assert.ok(headerBox.y < 240, "the disclosure is reachable at the top of a long imported list");
  assert.equal(await header.count(), 1);
  await header.click();
  const expand = page.getByRole("button", { name: "Expand Pinned Tabs · papers", exact: true });
  await expand.waitFor();
  await page.waitForFunction(() => globalThis.ardiaDemo.store.getState().profiles.default.pinnedCollapsed === true);
  assert.equal(await expand.getAttribute("aria-expanded"), "false");
  await page.waitForFunction(() => !document.body.textContent.includes("Deep Learning Alchemy 1"));
  assert.ok(await page.getByText("Web browser - Wikipedia", { exact: true }).isVisible());
  await capture("collapsed");
  await expand.focus();
  await page.keyboard.press("Enter");
  await header.waitFor();
  await page.getByText("Deep Learning Alchemy 1", { exact: true }).waitFor();
  await page.evaluate(() => { const s = globalThis.ardiaDemo.store.getState(); const t = Object.values(s.tabs).find((t) => t.customTitle === "Deep Learning Alchemy 1"); s.activate(t.id); });
  await header.click();
  await expand.waitFor();
  await page.getByText("Deep Learning Alchemy 1", { exact: true }).waitFor({ state: "visible" });
  await page.waitForFunction(() => !document.body.textContent.includes("Chatbot 2"));
  await capture("collapsed-active-pin");
  await page.evaluate(() => globalThis.ardiaDemo.store.getState().switchProfile("w_demo", "p_work"));
  await page.getByRole("button", { name: "Collapse Pinned Tabs · Work", exact: true }).waitFor();
  assert.ok(await page.getByText("Work bookmark", { exact: true }).isVisible());
  await capture("other-space");
  await page.evaluate(() => globalThis.ardiaDemo.store.getState().switchProfile("w_demo", "default"));
  await expand.waitFor();
  await page.evaluate(() => globalThis.ardiaDemo.store.getState().updateProfile("default", { name: "A very long Space name ".repeat(12) }));
  const long = page.getByRole("button", { name: /^Expand Pinned Tabs · A very long Space name/ });
  await long.waitFor();
  const longBox = await long.boundingBox();
  assert.ok(longBox && longBox.width <= 260 && longBox.height <= 40);
  await capture("long-name");
  const state = await page.evaluate(() => { const s = globalThis.ardiaDemo.store.getState(); return { pins: Object.values(s.tabs).filter((t) => t.profileId === "default" && t.pin?.as === "row").length, groups: Object.keys(s.groups).length, collapsed: s.profiles.default.pinnedCollapsed, workCollapsed: !!s.profiles.p_work.pinnedCollapsed }; });
  assert.deepEqual(state, { pins: 36, groups: 0, collapsed: true, workCollapsed: false });
  console.log(JSON.stringify({ passed: true, checks: ["36 imported root pins", "header above rows", "pointer collapse", "keyboard expand", "active pin kept", "Space isolation", "long names"], screenshots: output }));
} catch (error) {
  await page.screenshot({ path: resolve(output, "failure.png") });
  console.error(await page.evaluate(() => { const s = globalThis.ardiaDemo.store.getState(); return { active: s.windows.w_demo.activeTabIds, collapsed: s.profiles.default.pinnedCollapsed, text: document.body.textContent.slice(0, 1500) }; }));
  throw error;
} finally {
  await browser.close();
}
